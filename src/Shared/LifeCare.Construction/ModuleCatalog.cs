namespace LifeCare.Construction;

/// <summary>An opening a wall can host: its clear size, sill and offset along the wall, and whether people can pass.</summary>
public sealed record WallOpeningSpec(string Id, string Name, float WidthMeters, float HeightMeters, float SillMeters, float OffsetMeters, bool Passable,
    bool Vehicle = false, bool Glazed = false);

/// <summary>A wall finish: its display name, how long it holds against fire, and its colours for generated geometry.</summary>
public sealed record WallStyleSpec(string Id, string Name, int FireRatingMinutes, string Siding, string Trim, string Skirt, string Pattern);

/// <summary>
/// The rural town module pack (assets/modules/rural, generated by tools/blender/rural_modules/build_rural_pack.py) as
/// build data. Lot documents store these short ids; <see cref="LotGeometry"/> turns them into module ids, and the client
/// draws the matching GLBs. The palette mirrors the generator's so procedurally built curved walls match the modules.
/// </summary>
public static class ModuleCatalog
{
    public const string DefaultExteriorStyle = "lap_white";
    public const string InteriorStyle = "plaster";
    public const string NoOpening = "full";
    public const string DefaultFloorFinish = "wood";
    public const string DefaultRoofShape = "flat";
    public const string DefaultRoofFinish = "shingle";

    public static readonly IReadOnlyList<WallStyleSpec> WallStyles =
    [
        new("lap_white", "Wood siding (painted)", 20, "siding_white", "trim_white", "trim_white", "lap"),
        new("lap_natural", "Wood siding (natural)", 20, "siding_natural", "wood_dark", "wood_dark", "lap"),
        new("stucco", "Stucco", 60, "stucco", "trim_white", "concrete", "flat"),
        new("batten_green", "Board and batten (green)", 20, "batten_green", "trim_white", "trim_white", "batten"),
        new("batten_red", "Board and batten (barn red)", 20, "batten_red", "trim_white", "trim_white", "batten"),
        new("stone", "Stone", 120, "stone", "trim_white", "concrete", "stone"),
        new("plaster", "Interior plaster", 30, "drywall", "trim_white", "trim_white", "flat"),
    ];

    /// <summary>Openings, matching the pack's wall modules (wall_&lt;style&gt;_&lt;id&gt;). "passage" exists on curved walls only.</summary>
    public static readonly IReadOnlyList<WallOpeningSpec> Openings =
    [
        new(NoOpening, "Solid wall", 0, 0, 0, 0, false),
        new("door_wood", "Wood door", .9f, 2.1f, 0, 0, true),
        new("door_halfglass", "Half-window door", .9f, 2.1f, 0, 0, true, Glazed: true),
        new("door_screen", "Screen door", .9f, 2.1f, 0, 0, true),
        new("door_garage", "Garage door", 2.7f, 2.4f, 0, 0, true, Vehicle: true),
        new("door_barn", "Barn door (sliding)", 3.0f, 2.6f, 0, 0, true, Vehicle: true),
        new("win_small", "Small window", .6f, .6f, 1.4f, 0, false, Glazed: true),
        new("win_large", "Large window", 1.2f, 1.4f, .9f, 0, false, Glazed: true),
        new("win_shutter", "Shutter window", .9f, 1.3f, .9f, 0, false, Glazed: true),
        new("win_corner", "Corner window", .9f, 1.3f, .9f, 1.25f, false, Glazed: true),
        new("win_wide", "Wide window", 2.4f, 1.2f, .9f, 0, false, Glazed: true),
        new("passage", "Open passage", 1.2f, 2.3f, 0, 0, true),
    ];

    /// <summary>Openings a straight 4 m wall module provides.</summary>
    public static IEnumerable<WallOpeningSpec> StraightOpenings => Openings.Where(o => o.Id != "passage");

    /// <summary>Openings a curved wall can host; garage and barn doors need a straight wall.</summary>
    public static IEnumerable<WallOpeningSpec> CurvedOpenings => Openings.Where(o => o.Id is "door_wood" or "door_halfglass" or "passage" or "win_small" or "win_large" or "win_wide");

    public static readonly IReadOnlyList<(string Id, string Name, string ModuleId)> FloorFinishes =
    [
        ("wood", "Wood floor", "floor_wood"), ("tile", "Tile floor", "floor_tile"), ("concrete", "Concrete slab", "floor_concrete"),
        ("raised_wood", "Raised wood floor", "floor_raised_wood"),
    ];

    public static readonly IReadOnlyList<(string Id, string Name)> RoofShapes = [("flat", "Flat"), ("gable", "Gable"), ("hip", "Hip")];
    public static readonly IReadOnlyList<(string Id, string Name)> RoofFinishes = [("shingle", "Asphalt shingle"), ("metal_green", "Metal (green)"), ("metal_galv", "Metal (galvanized)")];

    public static WallStyleSpec? Style(string? id) => WallStyles.FirstOrDefault(s => s.Id == id);
    public static WallOpeningSpec? Opening(string? id) => Openings.FirstOrDefault(o => o.Id == id);
    public static bool IsFloorFinish(string? id) => FloorFinishes.Any(f => f.Id == id);
    public static bool IsRoofShape(string? id) => RoofShapes.Any(s => s.Id == id);
    public static bool IsRoofFinish(string? id) => RoofFinishes.Any(f => f.Id == id);

    public static string WallModule(string style, string opening) => $"wall_{style}_{opening}";
    public static string OuterCornerModule(string style) => $"corner_{style}_outer";
    public static string GableInfillModule(string style) => $"gable_infill_{style}";
    public static string FloorModule(string finish) => FloorFinishes.FirstOrDefault(f => f.Id == finish).ModuleId ?? "floor_wood";

    /// <summary>Linear RGB of the pack's palette (sRGB hex in the generator), for vertex-coloured generated meshes.</summary>
    public static (float R, float G, float B) Color(string material) => Palette.TryGetValue(material, out var hex) ? Linear(hex) : (1, 0, 1);

    private static (float, float, float) Linear(string hex)
    {
        static float Channel(string h, int i)
        {
            float c = Convert.ToInt32(h.Substring(i, 2), 16) / 255f;
            return c <= .04045f ? c / 12.92f : MathF.Pow((c + .055f) / 1.055f, 2.4f);
        }
        string h = hex.TrimStart('#');
        return (Channel(h, 0), Channel(h, 2), Channel(h, 4));
    }

    private static readonly Dictionary<string, string> Palette = new(StringComparer.Ordinal)
    {
        ["trim_white"] = "#ECEBE4", ["drywall"] = "#D9D3C7", ["siding_white"] = "#E4E2D6", ["siding_natural"] = "#9C7550",
        ["stucco"] = "#CDBB9B", ["batten_green"] = "#4E6B4A", ["batten_red"] = "#8E2A22", ["stone"] = "#8A857C", ["mortar"] = "#5F5B55",
        ["concrete"] = "#9E9C96", ["wood_dark"] = "#4D3826", ["wood_floor"] = "#A0703F", ["glass"] = "#8FB0C4", ["door_wood"] = "#6E4A2C",
        ["door_green"] = "#3E5A3C", ["brass"] = "#B08D47", ["metal_dark"] = "#2B2D30", ["counter_top"] = "#B9B2A4",
    };
}
